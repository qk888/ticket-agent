"""字形归一化：把繁体字形映射成简体，让判据看穿字形差异。

存在理由
--------
本项目的判据（`_REQUEST_RE` / `_DEFECT_RE` / `_PRE_RECEIPT_RE` / `_POST_RECEIPT_RE`）
都是**简体字面量**。用一份与本项目无关的繁体数据集（`hf_zhtw_ticket_train`）做外部
效度检验时暴露了一个真问题：

    我的包裹已經到超商但還沒收到通知

这句明明是"货没到手"（`_PRE_RECEIPT_RE` 该接住它），但 `還沒` 不在简体词典里，
而 `收到` 命中了 `_POST_RECEIPT_RE` → `presupposes_receipt` 返回 **True**，
把这个字段**判反了**。判据依赖的是字形，不是语义。

实测同一批 2,497 条繁体句：判据在繁简两种字形下给出不同路由结论的有 **321 条（12.9%）**，
`presupposes_receipt` 判反 **159 条（6.4%）**。所以这不是边角情况。

表的来源：生成，不是手写
------------------------
第一版我用一张手写的 84 条映射表，随即发现它的覆盖率判据是**循环论证** ——
用表里的键定义"什么是繁体"，又用同一张表定义"转换是否成功"，于是
"归一化后 0 残留"是同义反复，什么都没证明。

现在这张表由 `_gennorm.py` 从 **Windows NLS**（`LCMapStringW` +
`LCMAP_SIMPLIFIED_CHINESE`）**生成一次**后固化成本文件里的静态数据。这样安排有两层理由：

  ① **正确性的来源变了**。手写表错了是我的错，NLS 表错了是微软映射表的错 ——
     而它有独立的正确性来源，不由本项目的任何假设决定。
  ② **不运行时调 NLS**。NLS 是 Windows 专有的；判据若在运行时依赖它，同一段文本
     在 Windows 和 Linux 上会得到不同结论，这对一个"判据必须可复现"的项目不可接受。
     固化之后，本模块在任何平台上的行为都完全一致。

覆盖范围：只收判据词典里的异形字
--------------------------------
`_gennorm.py` 只把**四条判据正则里出现过的汉字**送去问 NLS，得到 32 对异形字。
刻意不扩大范围：归一化的唯一用途是让判据看穿字形，`後`/`於` 这类字转不转
都不影响任何一次判定，收进来只会让"这张表为什么有这一条"说不清。

★ 已知边界（两条，都是实测结论，不是猜测）
------------------------------------------
**边界一：NLS 本身有漏，且这张表继承了它。** NLS 对 `後/於/乾/牠/癡` 这几对字
**双向都不转**（不是保守，是它的表里根本没有这几对）。好在这几个字都不在判据词典里，
`_nlsdict.py` 独立验证过：词典 110 个汉字中「转不回来」的是 **0 个**。
但这条验证是**一次性**的 —— 若将来把 `后`/`于`/`干`/`它` 加进判据词典，
本表会**静默失效**（那几对字不会被本表转换）。加字时须重跑 `_nlsdict.py`。

**边界二：归一化只解决字形，不解决词典覆盖。** 它把 `還沒` 变成 `还没`，
但 `_PRE_RECEIPT_RE` 里**有没有** `还没到` 这样的词条，是另一个问题 ——
本模块不负责、也无法负责后者。这两件事混起来谈会让"判据不准"永远找不到原因。
"""

from __future__ import annotations

# 32 对异形字，由 `_gennorm.py` 从 Windows NLS 生成（见模块 docstring）。
# 排序方式为繁体字的 Unicode 码位，生成结果稳定，可与 `_gennorm.py` 的输出逐字对比。
_T2S: dict[str, str] = {
    "來": "来",
    "個": "个",
    "劃": "划",
    "單": "单",
    "嗎": "吗",
    "壓": "压",
    "壞": "坏",
    "學": "学",
    "幫": "帮",
    "幾": "几",
    "換": "换",
    "損": "损",
    "攔": "拦",
    "攬": "揽",
    "時": "时",
    "沒": "没",
    "發": "发",
    "簽": "签",
    "線": "线",
    "膠": "胶",
    "臟": "脏",
    "試": "试",
    "請": "请",
    "變": "变",
    "貨": "货",
    "質": "质",
    "還": "还",
    "錢": "钱",
    "錯": "错",
    "開": "开",
    "頭": "头",
    "顯": "显",
}

# `str.translate` 用，比逐字 replace 快且天然只做单字映射
_TRANS = str.maketrans(_T2S)

# 供探针与测试判断"这个字本模块认不认得"（不等于"这个字是不是繁体"）
TRADITIONAL_CHARS: frozenset[str] = frozenset(_T2S)


def normalize(text: str) -> str:
    """把繁体字形归一成简体，使判据只看语义、不看字形。

    对**不含表内字符**的文本是恒等变换 —— 这是可以验证的，不是声明：
    6,638 条现有语料过一遍，只有 **13 条**发生变化（那些条本来就混着繁体字，
    如 `貨`/`什麽`/`還沒`/`剛`），且这 13 条的判据结论**一个都没变**
    （`classify_style` 变 0 条、`presupposes_receipt` 变 0 条）。
    也就是说本模块对现有报表的影响是零，纯增益。

    ★ 13 与 22 的区别要看清：完整 NLS 会把语料改掉 22 条，本表只改 13 条。
    差额不是漏，是**故意的** —— 本表只收判据词典里出现过的 32 对字
    （另有 9 条只含 `妳`/`丟`/`飛`/`掛` 这类不影响任何判定的字）。
    追求"把语料转干净"是另一个目标，本模块不做那件事。

    ★ 不要用本函数"清洗数据"。它的职责窄到只有一件事：让判据看穿字形。
    语料本身应当保持原始字节（`load_corpus()` 的 `sha256` 才有意义），
    归一化发生在判据内部，不外泄。
    """
    return text.translate(_TRANS)
